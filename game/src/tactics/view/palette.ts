const cache = new Map<string, number>();

/** Colour `ramp` index `i` (dark → light), e.g. pal('grass', 3). */
export function pal(ramp: string, i: number): number {
  const fb = FALLBACK[ramp];
  const idx = fb ? Math.max(0, Math.min(fb.length - 1, i)) : i;
  const name = `${ramp}${idx}`;
  const hit = cache.get(name);
  if (hit !== undefined) return hit;
  let v: number | undefined;
  try { v = G.art?.color(name); } catch { v = undefined; }
  if (v === undefined || v === 0xff00ff || (v === 0xffffff && !(ramp === 'white' && idx === 4))) v = fb?.[idx] ?? 0xff00ff;
  cache.set(name, v);
  return v;
}

/** Number of steps in a ramp. */
export const rampLen = (ramp: string) => FALLBACK[ramp]?.length ?? 6;

export const css = (c: number) => `#${(c >>> 0).toString(16).padStart(6, '0')}`;

export function mix(a: number, b: number, t: number): number {
  const ar = (a >> 16) & 255, ag = (a >> 8) & 255, ab = a & 255;
  const br = (b >> 16) & 255, bg = (b >> 8) & 255, bb = b & 255;
  return (Math.round(ar + (br - ar) * t) << 16) | (Math.round(ag + (bg - ag) * t) << 8) | Math.round(ab + (bb - ab) * t);
}
